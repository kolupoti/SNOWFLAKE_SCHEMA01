CREATE OR REPLACE TABLE DCM_ADMIN_DB.PUBLIC.EMPLOYEE (
    EMPLOYEE_ID NUMBER(10,0) NOT NULL,
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    EMAIL VARCHAR(255),
    DEPARTMENT VARCHAR(100),
    SALARY NUMBER(12,2),
    HIRE_DATE DATE,
    CREATED_DATE TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EMPLOYEE_ID)
);

CREATE OR REPLACE TABLE DCM_ADMIN_DB.PUBLIC.DEPARTMENT (
    DEPARTMENT_ID NUMBER(10,0) NOT NULL,
    DEPARTMENT_NAME VARCHAR(100),
    LOCATION VARCHAR(100),
    MANAGER_ID NUMBER(10,0),
    CREATED_DATE TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DEPARTMENT PRIMARY KEY (DEPARTMENT_ID)
);

CREATE OR REPLACE VIEW DCM_ADMIN_DB.PUBLIC.VW_EMPLOYEE_DETAILS AS
SELECT
    E.EMPLOYEE_ID,
    E.FIRST_NAME,
    E.LAST_NAME,
    E.EMAIL,
    E.DEPARTMENT,
    E.SALARY,
    E.HIRE_DATE,
    D.LOCATION AS DEPARTMENT_LOCATION
FROM DCM_ADMIN_DB.PUBLIC.EMPLOYEE E
LEFT JOIN DCM_ADMIN_DB.PUBLIC.DEPARTMENT D
    ON E.DEPARTMENT = D.DEPARTMENT_NAME;


CREATE OR REPLACE VIEW DCM_ADMIN_DB.PUBLIC.VW_DEPARTMENT_SUMMARY AS
SELECT
    D.DEPARTMENT_ID,
    D.DEPARTMENT_NAME,
    D.LOCATION,
    COUNT(E.EMPLOYEE_ID) AS EMPLOYEE_COUNT,
    SUM(E.SALARY) AS TOTAL_SALARY,
    AVG(E.SALARY) AS AVG_SALARY
FROM DCM_ADMIN_DB.PUBLIC.DEPARTMENT D
LEFT JOIN DCM_ADMIN_DB.PUBLIC.EMPLOYEE E
    ON D.DEPARTMENT_NAME = E.DEPARTMENT
GROUP BY
    D.DEPARTMENT_ID,
    D.DEPARTMENT_NAME,
    D.LOCATION;


