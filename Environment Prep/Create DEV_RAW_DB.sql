--Create database
CREATE DATABASE IF NOT EXISTS DEV_RAW_DB;
--Create schema
USE DATABASE DEV_RAW_DB;
CREATE SCHEMA IF NOT EXISTS ALIP;

--Create Table 1 – CUSTOMER
CREATE OR REPLACE TABLE DEV_RAW_DB.ALIP.CUSTOMER
(
    CUSTOMER_ID     NUMBER(10,0) NOT NULL,
    FIRST_NAME      VARCHAR(100),
    LAST_NAME       VARCHAR(100),
    EMAIL           VARCHAR(255),
    PHONE_NUMBER    VARCHAR(20),
    ADDRESS         VARCHAR(500),
    CITY            VARCHAR(100),
    STATE           VARCHAR(100),
    ZIP_CODE        VARCHAR(20),
    CREATED_DATE    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_DATE    TIMESTAMP_NTZ
);

--Create Table 2 – CUSTOMER_ORDERS
CREATE OR REPLACE TABLE DEV_RAW_DB.ALIP.CUSTOMER_ORDERS
(
    ORDER_ID        NUMBER(10,0) NOT NULL,
    CUSTOMER_ID     NUMBER(10,0),
    ORDER_DATE      DATE,
    ORDER_AMOUNT    NUMBER(12,2),
    ORDER_STATUS    VARCHAR(50),
    PAYMENT_METHOD  VARCHAR(50),
    CREATED_DATE    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_DATE    TIMESTAMP_NTZ
);

