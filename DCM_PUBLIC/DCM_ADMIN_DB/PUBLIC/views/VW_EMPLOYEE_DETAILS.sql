DEFINE view DCM_ADMIN_DB.PUBLIC.VW_EMPLOYEE_DETAILS(
	EMPLOYEE_ID,
	FIRST_NAME,
	LAST_NAME,
	EMAIL,
	DEPARTMENT,
	SALARY,
	HIRE_DATE,
	DEPARTMENT_LOCATION
) as
SELECT
    E.EMPLOYEE_ID,
    E.FIRST_NAME,
    E.LAST_NAME,
    E.EMAIL,
    E.DEPARTMENT,
    E.SALARY,
    E.HIRE_DATE,
    D.LOCATION AS DEPARTMENT_LOCATION
FROM DCM_ADMIN_DB.PUBLIC.EMPLOYEE E
LEFT JOIN DCM_ADMIN_DB.PUBLIC.DEPARTMENT D
    ON E.DEPARTMENT = D.DEPARTMENT_NAME;