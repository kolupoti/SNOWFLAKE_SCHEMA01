DEFINE view DCM_ADMIN_DB.PUBLIC.VW_DEPARTMENT_SUMMARY(
	DEPARTMENT_ID,
	DEPARTMENT_NAME,
	LOCATION,
	EMPLOYEE_COUNT,
	TOTAL_SALARY,
	AVG_SALARY
) as
SELECT
    D.DEPARTMENT_ID,
    D.DEPARTMENT_NAME,
    D.LOCATION,
    COUNT(E.EMPLOYEE_ID) AS EMPLOYEE_COUNT,
    SUM(E.SALARY) AS TOTAL_SALARY,
    AVG(E.SALARY) AS AVG_SALARY
FROM DCM_ADMIN_DB.PUBLIC.DEPARTMENT D
LEFT JOIN DCM_ADMIN_DB.PUBLIC.EMPLOYEE E
    ON D.DEPARTMENT_NAME = E.DEPARTMENT
GROUP BY
    D.DEPARTMENT_ID,
    D.DEPARTMENT_NAME,
    D.LOCATION;